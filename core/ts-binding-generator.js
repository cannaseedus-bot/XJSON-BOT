/**
 * KUHUL TypeScript Binding Generator
 * Generates .d.ts files from ASX capability declarations
 *
 * @version 1.0.0
 * @status frozen
 * @authority AST_IS_LAW
 *
 * This generator:
 * - Reads ASX capability schemas
 * - Emits TypeScript declaration files (.d.ts)
 * - Provides IDE tooling (autocomplete, type checking)
 * - Does NOT emit executable code (bindings only)
 */

