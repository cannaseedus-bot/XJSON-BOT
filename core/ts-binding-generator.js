function generateFromFile(inputPath, outputPath) {
  const fs = require('fs');
  const path = require('path');

  const generator = new TypeScriptBindingGenerator();

  // Read schema
  const schemaText = fs.readFileSync(inputPath, 'utf8');
  const schema = JSON.parse(schemaText);

  // Generate
  const declarations = generator.generate(schema);

  // Write output
  if (outputPath) {
    fs.writeFileSync(outputPath, declarations);
    console.log(`Generated: ${outputPath}`);
  } else {
    console.log(declarations);
  }

  // Also generate base types if not exists
  const basePath = path.join(path.dirname(outputPath || '.'), 'kuhul-base.d.ts');
  if (!fs.existsSync(basePath)) {
    fs.writeFileSync(basePath, generator.generateBaseTypes());
    console.log(`Generated: ${basePath}`);
  }
}

