const BASE_DECLARATIONS = `
// ============================================================
// KUHUL Base Types
// Generated by KUHUL TypeScript Binding Generator v1.0.0
// ============================================================

/**
 * Host runtime identifiers
 */
export type KUHULHostId = 'python' | 'node' | 'wasm' | 'native' | 'jvm' | 'dotnet';

/**
 * Universal value type for KPI transport
 */
export type KUHULValue =
  | null
  | boolean
  | number
  | string
  | KUHULValue[]
  | { [key: string]: KUHULValue }
  | KUHULHandle
  | KUHULBytes;

/**
 * Binary data wrapper
 */
export interface KUHULBytes {
  readonly bytes_b64: string;
}

/**
 * Opaque handle to foreign object
 */
export interface KUHULHandle {
  readonly type: 'handle';
  readonly handle_id: number;
  readonly host: KUHULHostId;
}

/**
 * Object handle with type info
 */
export interface KUHULObjectHandle extends KUHULHandle {
  readonly type_name: string;
}

/**
 * Module handle
 */
export interface KUHULModuleHandle extends KUHULHandle {
  readonly module: string;
}

/**
 * Execution trace for replay verification
 */
export interface KUHULExecutionTrace {
  readonly call_id: string;
  readonly timestamp_ms: number;
  readonly duration_ms: number;
  readonly input_hash: string;
  readonly output_hash: string;
  readonly host: KUHULHostId;
}

/**
 * Error from foreign execution
 */
export interface KUHULError {
  readonly code: string;
  readonly message: string;
  readonly host: KUHULHostId;
  readonly traceback?: string;
}

/**
 * Result from foreign call
 */
export interface KUHULResult<T = KUHULValue> {
  readonly success: boolean;
  readonly result: T | null;
  readonly error: KUHULError | null;
  readonly trace: KUHULExecutionTrace;
}

/**
 * KUHUL Glyph base interface
 */
export interface KUHULGlyph {
  readonly name: string;
  readonly category: 'pure' | 'effect';
  readonly deterministic: boolean;
  readonly replayable: boolean;
}

/**
 * KUHUL Body (physics object)
 */
export interface KUHULBody {
  readonly id: string;
  readonly position: [number, number, number];
  readonly velocity: [number, number, number];
  readonly mass: number;
}

/**
 * KUHUL Constraint
 */
export interface KUHULConstraint {
  readonly id: string;
  readonly type: string;
  readonly bodies: string[];
}

/**
 * KUHUL Field
 */
export interface KUHULField {
  readonly id: string;
  readonly type: 'scalar' | 'vector' | 'tensor';
  readonly dimensions: number[];
}

/**
 * KPI binding - describes a capability without execution authority
 */
export interface KUHULBinding<TInput = unknown, TOutput = unknown> {
  readonly host: KUHULHostId;
  readonly module: string;
  readonly symbol: string;
  readonly inputs: TInput;
  readonly outputs: TOutput;
}

/**
 * Foreign function call descriptor
 */
export interface ForeignCallDescriptor<TArgs extends any[] = any[], TResult = KUHULValue> {
  readonly host: KUHULHostId;
  readonly module: string;
  readonly symbol: string;
  (this: void, ...args: TArgs): Promise<KUHULResult<TResult>>;
}

/**
 * Foreign class constructor descriptor
 */
export interface ForeignClassDescriptor<TArgs extends any[] = any[], TInstance = KUHULObjectHandle> {
  readonly host: KUHULHostId;
  readonly module: string;
  readonly className: string;
  new (...args: TArgs): Promise<TInstance>;
}
`;

// ============================================================
// Generator Class
// ============================================================

class TypeScriptBindingGenerator {
  constructor() {
    this.output = [];
    this.imports = new Set();
    this.generatedTypes = new Set();
  }

  /**
   * Generate .d.ts from ASX capability schema
   */
  generate(schema) {
    this.output = [];
    this.imports.clear();
    this.generatedTypes.clear();

    // Header
    this.output.push('// ============================================================');
    this.output.push(`// ${schema['@title'] || 'KUHUL Bindings'}`);
    this.output.push('// Generated by KUHUL TypeScript Binding Generator v1.0.0');
    this.output.push('// ============================================================');
    this.output.push('');
    this.output.push("import type { KUHULValue, KUHULResult, KUHULHandle, KUHULObjectHandle, KUHULHostId, KUHULExecutionTrace, KUHULError } from './kuhul-base';");
    this.output.push('');

    // Generate from schema
    if (schema['@glyphs']) {
      this.generateGlyphs(schema['@glyphs']);
    }

    if (schema['@types']) {
      this.generateTypes(schema['@types']);
    }

    if (schema['@capabilities'] || schema['@python_adapter']?.capabilities) {
      const capabilities = schema['@capabilities'] || schema['@python_adapter'].capabilities;
      this.generateCapabilities(capabilities);
    }

    if (schema['@adapters']) {
      this.generateAdapters(schema['@adapters']);
    }

    return this.output.join('\n');
  }

  /**
   * Generate base type declarations
   */
  generateBaseTypes() {
    return BASE_DECLARATIONS;
  }

  /**
   * Generate glyph type declarations
   */
  generateGlyphs(glyphs) {
    this.output.push('// ============================================================');
    this.output.push('// Glyph Declarations');
    this.output.push('// ============================================================');
    this.output.push('');

    for (const [name, glyph] of Object.entries(glyphs)) {
      if (typeof glyph !== 'object') continue;

      this.output.push(`/**`);
      this.output.push(` * ${glyph.description || name}`);
      this.output.push(` * @category ${glyph.category || 'effect'}`);
      this.output.push(` * @deterministic ${glyph.deterministic || false}`);
      this.output.push(` */`);

      // Generate input type
      const inputTypeName = `${name}Input`;
      const outputTypeName = `${name}Output`;

      if (glyph.inputs) {
        this.output.push(`export interface ${inputTypeName} {`);
        for (const [fieldName, fieldDef] of Object.entries(glyph.inputs)) {
          const tsType = this.mapType(fieldDef.type || 'unknown');
          const optional = fieldDef.required === false ? '?' : '';
          const description = fieldDef.description ? ` /** ${fieldDef.description} */` : '';
          this.output.push(`  readonly ${fieldName}${optional}: ${tsType};${description}`);
        }
        this.output.push('}');
        this.output.push('');
      }

      // Generate output type
      if (glyph.outputs) {
        this.output.push(`export interface ${outputTypeName} {`);
        for (const [fieldName, fieldDef] of Object.entries(glyph.outputs)) {
          const tsType = this.mapType(fieldDef.type || 'unknown');
          const description = fieldDef.description ? ` /** ${fieldDef.description} */` : '';
          this.output.push(`  readonly ${fieldName}: ${tsType};${description}`);
        }
        this.output.push('}');
        this.output.push('');
      }

      // Generate glyph function declaration
      const hasInputs = glyph.inputs && Object.keys(glyph.inputs).length > 0;
      const hasOutputs = glyph.outputs && Object.keys(glyph.outputs).length > 0;

      this.output.push(`export declare function ${name}(`);
      if (hasInputs) {
        this.output.push(`  input: ${inputTypeName}`);
      }
      this.output.push(`): Promise<KUHULResult<${hasOutputs ? outputTypeName : 'void'}>>;`);
      this.output.push('');
    }
  }

  /**
   * Generate type declarations from schema
   */
  generateTypes(types) {
    this.output.push('// ============================================================');
    this.output.push('// Type Declarations');
    this.output.push('// ============================================================');
    this.output.push('');

    for (const [name, typeDef] of Object.entries(types)) {
      if (this.generatedTypes.has(name)) continue;
      this.generatedTypes.add(name);

      if (typeDef.enum) {
        // Enum type
        const values = typeDef.enum.map(v => `'${v}'`).join(' | ');
        this.output.push(`export type ${name} = ${values};`);
      } else if (typeDef.oneOf) {
        // Union type
        const types = typeDef.oneOf.map(t => this.mapType(t)).join(' | ');
        this.output.push(`export type ${name} = ${types};`);
      } else if (typeDef.properties) {
        // Object type
        this.output.push(`export interface ${name} {`);
        for (const [propName, propDef] of Object.entries(typeDef.properties)) {
          const tsType = this.mapType(propDef.type || propDef['$ref'] || 'unknown');
          const optional = !typeDef.required?.includes(propName) ? '?' : '';
          this.output.push(`  readonly ${propName}${optional}: ${tsType};`);
        }
        this.output.push('}');
      }
      this.output.push('');
    }
  }

  /**
   * Generate capability bindings
   */
  generateCapabilities(capabilities) {
    this.output.push('// ============================================================');
    this.output.push('// Capability Bindings');
    this.output.push('// ============================================================');
    this.output.push('');

    for (const [name, capability] of Object.entries(capabilities)) {
      const moduleName = capability.module || name;
      const functions = capability.functions || [];

      this.output.push(`/**`);
      this.output.push(` * ${capability.description || name}`);
      this.output.push(` * @module ${moduleName}`);
      this.output.push(` */`);
      this.output.push(`export declare namespace ${this.sanitizeIdentifier(name)} {`);

      for (const func of functions) {
        const funcName = func.includes('.') ? func.split('.').pop() : func;
        const sanitizedName = this.sanitizeIdentifier(funcName);

        this.output.push(`  /**`);
        this.output.push(`   * Binding to ${moduleName}.${func}`);
        this.output.push(`   */`);
        this.output.push(`  export function ${sanitizedName}(`);
        this.output.push(`    ...args: KUHULValue[]`);
        this.output.push(`  ): Promise<KUHULResult>;`);
        this.output.push('');
      }

      this.output.push('}');
      this.output.push('');
    }
  }

  /**
   * Generate language adapter declarations
   */
  generateAdapters(adapters) {
    this.output.push('// ============================================================');
    this.output.push('// Language Adapters');
    this.output.push('// ============================================================');
    this.output.push('');

    for (const [langId, adapter] of Object.entries(adapters)) {
      if (typeof adapter !== 'object') continue;

      const name = this.sanitizeIdentifier(langId);

      this.output.push(`/**`);
      this.output.push(` * ${langId} Language Adapter`);
      this.output.push(` * @family ${adapter.surface?.family || 'unknown'}`);
      this.output.push(` */`);
      this.output.push(`export declare namespace ${name}Adapter {`);
      this.output.push(`  export const langId: '${langId}';`);
      this.output.push(`  export const family: '${adapter.surface?.family || 'unknown'}';`);
      this.output.push('');

      // Parse function
      this.output.push(`  /**`);
      this.output.push(`   * Parse ${langId} source to canonical AST`);
      this.output.push(`   */`);
      this.output.push(`  export function parse(source: string): Promise<ASTNode>;`);
      this.output.push('');

      // Print function
      this.output.push(`  /**`);
      this.output.push(`   * Print canonical AST to ${langId} source`);
      this.output.push(`   */`);
      this.output.push(`  export function print(ast: ASTNode): string;`);
      this.output.push('');

      this.output.push('}');
      this.output.push('');
    }

    // AST Node type
    this.output.push(`/**`);
    this.output.push(` * Canonical AST Node (language-agnostic)`);
    this.output.push(` */`);
    this.output.push(`export interface ASTNode {`);
    this.output.push(`  readonly type: string;`);
    this.output.push(`  readonly id?: string;`);
    this.output.push(`  readonly loc?: SourceLocation;`);
    this.output.push(`  readonly [key: string]: unknown;`);
    this.output.push(`}`);
    this.output.push('');

    this.output.push(`export interface SourceLocation {`);
    this.output.push(`  readonly start: Position;`);
    this.output.push(`  readonly end: Position;`);
    this.output.push(`  readonly source?: string;`);
    this.output.push(`}`);
    this.output.push('');

    this.output.push(`export interface Position {`);
    this.output.push(`  readonly line: number;`);
    this.output.push(`  readonly col: number;`);
    this.output.push(`  readonly off: number;`);
    this.output.push(`}`);
  }

  /**
   * Generate Python-specific bindings
   */
  generatePythonBindings(capabilities) {
    const lines = [];

    lines.push('// ============================================================');
    lines.push('// Python Capability Bindings');
    lines.push('// Generated from Python Adapter Contract v1');
    lines.push('// ============================================================');
    lines.push('');
    lines.push("import type { KUHULValue, KUHULResult, KUHULObjectHandle } from './kuhul-base';");
    lines.push('');

    // NumPy
    lines.push('/**');
    lines.push(' * NumPy array operations');
    lines.push(' * @module numpy');
    lines.push(' */');
    lines.push('export declare namespace numpy {');
    lines.push('  export interface NDArray extends KUHULObjectHandle {');
    lines.push('    readonly dtype: string;');
    lines.push('    readonly shape: number[];');
    lines.push('  }');
    lines.push('');
    lines.push('  export function array(data: number[] | number[][]): Promise<KUHULResult<NDArray>>;');
    lines.push('  export function zeros(shape: number[]): Promise<KUHULResult<NDArray>>;');
    lines.push('  export function ones(shape: number[]): Promise<KUHULResult<NDArray>>;');
    lines.push('  export function dot(a: NDArray, b: NDArray): Promise<KUHULResult<NDArray>>;');
    lines.push('  export function matmul(a: NDArray, b: NDArray): Promise<KUHULResult<NDArray>>;');
    lines.push('  export function transpose(a: NDArray): Promise<KUHULResult<NDArray>>;');
    lines.push('  export function reshape(a: NDArray, shape: number[]): Promise<KUHULResult<NDArray>>;');
    lines.push('}');
    lines.push('');

    // PyTorch
    lines.push('/**');
    lines.push(' * PyTorch tensor operations');
    lines.push(' * @module torch');
    lines.push(' */');
    lines.push('export declare namespace torch {');
    lines.push('  export interface Tensor extends KUHULObjectHandle {');
    lines.push('    readonly dtype: string;');
    lines.push('    readonly shape: number[];');
    lines.push('    readonly device: string;');
    lines.push('  }');
    lines.push('');
    lines.push('  export function tensor(data: number[] | number[][]): Promise<KUHULResult<Tensor>>;');
    lines.push('  export function zeros(shape: number[]): Promise<KUHULResult<Tensor>>;');
    lines.push('  export function ones(shape: number[]): Promise<KUHULResult<Tensor>>;');
    lines.push('  export function randn(shape: number[]): Promise<KUHULResult<Tensor>>;');
    lines.push('  export function matmul(a: Tensor, b: Tensor): Promise<KUHULResult<Tensor>>;');
    lines.push('');
    lines.push('  export namespace nn {');
    lines.push('    export interface Module extends KUHULObjectHandle {}');
    lines.push('    export function Linear(inFeatures: number, outFeatures: number): Promise<KUHULResult<Module>>;');
    lines.push('    export function ReLU(): Promise<KUHULResult<Module>>;');
    lines.push('  }');
    lines.push('}');
    lines.push('');

    // Transformers
    lines.push('/**');
    lines.push(' * HuggingFace Transformers');
    lines.push(' * @module transformers');
    lines.push(' */');
    lines.push('export declare namespace transformers {');
    lines.push('  export interface Tokenizer extends KUHULObjectHandle {}');
    lines.push('  export interface Model extends KUHULObjectHandle {}');
    lines.push('  export interface Pipeline extends KUHULObjectHandle {}');
    lines.push('');
    lines.push('  export namespace AutoTokenizer {');
    lines.push('    export function from_pretrained(modelId: string): Promise<KUHULResult<Tokenizer>>;');
    lines.push('  }');
    lines.push('');
    lines.push('  export namespace AutoModel {');
    lines.push('    export function from_pretrained(modelId: string): Promise<KUHULResult<Model>>;');
    lines.push('  }');
    lines.push('');
    lines.push('  export function pipeline(task: string, options?: { model?: string }): Promise<KUHULResult<Pipeline>>;');
    lines.push('}');
    lines.push('');

    // PIL
    lines.push('/**');
    lines.push(' * Pillow image processing');
    lines.push(' * @module PIL');
    lines.push(' */');
    lines.push('export declare namespace PIL {');
    lines.push('  export interface Image extends KUHULObjectHandle {');
    lines.push('    readonly mode: string;');
    lines.push('    readonly size: [number, number];');
    lines.push('  }');
    lines.push('');
    lines.push('  export function open(path: string): Promise<KUHULResult<Image>>;');
    lines.push('  export function fromarray(data: KUHULValue): Promise<KUHULResult<Image>>;');
    lines.push('}');

    return lines.join('\n');
  }

  /**
   * Map KPI type to TypeScript type
   */
  mapType(kpiType) {
    if (!kpiType) return 'unknown';

    // Direct mapping
    if (KPI_TO_TS_TYPES[kpiType]) {
      return KPI_TO_TS_TYPES[kpiType];
    }

    // Handle $ref
    if (typeof kpiType === 'object' && kpiType['$ref']) {
      const ref = kpiType['$ref'];
      const typeName = ref.split('/').pop();
      return typeName;
    }

    // Handle array notation
    if (kpiType.endsWith('[]')) {
      const elementType = kpiType.slice(0, -2);
      return `${this.mapType(elementType)}[]`;
    }

    // Handle Record
    if (kpiType.startsWith('Record<')) {
      return kpiType; // Pass through
    }

    // Handle union (e.g., "Error | null")
    if (kpiType.includes(' | ')) {
      return kpiType.split(' | ').map(t => this.mapType(t.trim())).join(' | ');
    }

    // Fallback
    return kpiType;
  }

  /**
   * Sanitize identifier for TypeScript
   */
  sanitizeIdentifier(name) {
    // Replace invalid characters
    let sanitized = name.replace(/[^a-zA-Z0-9_$]/g, '_');

    // Ensure doesn't start with number
    if (/^[0-9]/.test(sanitized)) {
      sanitized = '_' + sanitized;
    }

    // Handle reserved words
    const reserved = ['break', 'case', 'catch', 'class', 'const', 'continue',
      'debugger', 'default', 'delete', 'do', 'else', 'enum', 'export',
      'extends', 'false', 'finally', 'for', 'function', 'if', 'import',
      'in', 'instanceof', 'new', 'null', 'return', 'super', 'switch',
      'this', 'throw', 'true', 'try', 'typeof', 'var', 'void', 'while',
      'with', 'yield'];

    if (reserved.includes(sanitized.toLowerCase())) {
      sanitized = '_' + sanitized;
    }

    return sanitized;
  }
}

